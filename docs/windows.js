// обратный расчёт цепочки
function goCalc(cargoId, perMonth) {
  $("cargo").value = cargoId; fillModes();
  $("vol").value = Math.max(1, Math.ceil(perMonth)); $("vol").oninput();
  document.querySelector('[data-tab="t-calc"]').click();
}
function chain() {
  const D = Math.max(0, +$("chDemand").value || 0), well = Math.max(1, +$("chWell").value || 1);
  const a = (+$("chA1").value || 1) / (+$("chA2").value || 1), b = (+$("chB1").value || 1) / (+$("chB2").value || 1);
  const oil = D * b, crude = oil * a, load = crude / well * 100;
  const legs = [
    ["Скважина → НПЗ 1", "Сырая нефть", "crude", crude],
    ["НПЗ 1 → НПЗ 2", "Нефть", "oil", oil],
    ["НПЗ 2 → Город", "Топливо", "fuel", D]
  ];
  $("chainFlow").innerHTML = `
    <div class="node"><b>Скважина</b><small>добывает до ${fmt(well)}</small></div><i>→</i>
    <div class="node"><b>НПЗ 1</b><small>${$("chA1").value}:${$("chA2").value}</small></div><i>→</i>
    <div class="node"><b>НПЗ 2</b><small>${$("chB1").value}:${$("chB2").value}</small></div><i>→</i>
    <div class="node end"><b>Город</b><small>просит ${fmt(D)}</small></div>`;
  $("chainOut").innerHTML = `
    <div class="tablewrap"><table class="legs"><thead><tr><th>Плечо</th><th>Груз</th><th>В год</th><th>В месяц</th><th></th></tr></thead><tbody>
    ${legs.map(([l, n, id, y]) => `<tr><td>${l}</td><td>${n}</td><td><b>${+y.toFixed(1)}</b></td><td>${+(y / 12).toFixed(1)}</td>
      <td><button class="btn sm" data-c="${id}" data-v="${y / 12}">Транспорт →</button></td></tr>`).join("")}
    </tbody></table></div>
    <div class="steps">
      <p><b>Как считали:</b></p>
      <ol>
        <li>Городу нужно <b>${fmt(D)}</b> топлива в год.</li>
        <li>НПЗ 2 (${$("chB1").value} нефти → ${$("chB2").value} топлива): ${fmt(D)} × ${+b.toFixed(2)} = <b>${+oil.toFixed(1)}</b> нефти.</li>
        <li>НПЗ 1 (${$("chA1").value} сырой → ${$("chA2").value} нефти): ${+oil.toFixed(1)} × ${+a.toFixed(2)} = <b>${+crude.toFixed(1)}</b> сырой нефти.</li>
        <li>Скважина загружена на <b>${load.toFixed(0)}%</b> (${+crude.toFixed(1)} из ${fmt(well)}).${load < 50 ? " Мощности много: подключите к НПЗ 2 ещё города, которым нужно топливо — поток и доход вырастут." : load > 100 ? " Не хватает: подключите ещё одну скважину." : ""}</li>
      </ol>
      <p class="muted">Кнопка «Транспорт →» переносит объём в калькулятор: останется указать расстояние и выбрать вид транспорта. При малом потоке (единицы в месяц) хватит одной машины на плечо — не стройте железную дорогу, пока спрос не вырос.</p>
    </div>`;
  $("chainOut").querySelectorAll("button[data-c]").forEach(bt => bt.onclick = () => goCalc(bt.dataset.c, +bt.dataset.v));
}
["chDemand", "chA1", "chA2", "chB1", "chB2", "chWell"].forEach(id => $(id).oninput = chain);
chain();
